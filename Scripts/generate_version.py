#!/usr/bin/env python3
"""Validate Resources/version.json and emit Sources/ZLModVersionData.h."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def load_version_metadata(path: Path) -> dict[str, object]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("version manifest must be a JSON object")
    version = payload.get("version")
    build_number = payload.get("buildNumber")
    build_label = payload.get("buildLabel")
    tag = payload.get("tag")
    edition = payload.get("edition", "")
    if not isinstance(version, str) or not version.strip():
        raise ValueError("version must be a non-empty string")
    if not isinstance(build_number, int) or build_number <= 0:
        raise ValueError("buildNumber must be a positive integer")
    if not isinstance(build_label, str) or not build_label.strip():
        raise ValueError("buildLabel must be a non-empty string")
    if not isinstance(tag, str) or not tag.strip():
        raise ValueError("tag must be a non-empty string")
    if not isinstance(edition, str):
        raise ValueError("edition must be a string")
    expected_label = f"Build {build_number}"
    expected_tag = f"build-{build_number}"
    if build_label != expected_label:
        raise ValueError(f"buildLabel {build_label!r} does not match {expected_label!r}")
    if tag != expected_tag:
        raise ValueError(f"tag {tag!r} does not match {expected_tag!r}")
    return {
        "version": version,
        "buildNumber": build_number,
        "buildLabel": build_label,
        "tag": tag,
        "edition": edition,
    }


def objc_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'@"{escaped}"'


def render_header(meta: dict[str, object]) -> str:
    return (
        "// Generated by Scripts/generate_version.py from Resources/version.json. Do not edit.\n"
        "#ifndef ZLMOD_VERSION_DATA_H\n"
        "#define ZLMOD_VERSION_DATA_H\n"
        "\n"
        f"#define ZLMOD_VERSION       {objc_string(str(meta['version']))}\n"
        f"#define ZLMOD_BUILD         {objc_string(str(meta['buildLabel']))}\n"
        f"#define ZLMOD_BUILD_NUMBER  {int(meta['buildNumber'])}\n"
        f"#define ZLMOD_RELEASE_TAG   {objc_string(str(meta['tag']))}\n"
        f"#define ZLMOD_EDITION       {objc_string(str(meta['edition']))}\n"
        "\n"
        "#endif /* ZLMOD_VERSION_DATA_H */\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("manifest", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        meta = load_version_metadata(args.manifest)
        rendered = render_header(meta)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8", newline="\n")
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(error, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
